def run_editor_checks(browser, base, check, request, state, draft, leader, command, run):
    context = browser.new_context(viewport={'width': 1440, 'height': 980})
    try:
        page = context.new_page(); page.goto(base)
        page.wait_for_function('window.workbenchUI !== undefined')
        check(page.locator('#bar').is_visible() and page.locator('#open-commands').is_visible(), 'one bottom status bar carries the focused buffer and the commands opener')
        finder(page, 'cursor')
        page.keyboard.press('Enter')
        command(page, 'new')
        check(state(page)['mode'] == 'Normal', 'new drafts enter editable Source directly')
        page.keyboard.press('i'); page.keyboard.type('([{"')
        check(draft(page)['text'] == '([{"', 'typing delimiters does not insert automatic closing characters')
        page.keyboard.press('Escape'); page.keyboard.type('ggdG')
        raw = '# Plan\nIntroduction.\n\n## Mechanics\nImplementation.\n\n```md\n# Literal heading\n```\n\n- First item\n- Second item\n\n> # Quoted heading\n> Quoted body.\n\n# Next\nContinuation.\n\nAppendix\n========\nSources.\n'
        page.keyboard.press('i'); page.keyboard.insert_text(raw); page.keyboard.press('Escape'); page.keyboard.type('gg')
        check(page.locator('.sac-section-gutter button').count() == 4, 'only document Markdown headings get folding controls')
        page.keyboard.type('zc')
        check(page.locator('.cm-foldPlaceholder').count() == 1 and draft(page)['text'] == raw, 'zc folds a Markdown section without changing its text')
        page.keyboard.press('j')
        point = next(p['position']['head'] for p in state(page)['panes'] if p['id'] == state(page)['focus'])
        check(point >= raw.index('# Next'), 'Vim j moves past a closed section rather than reopening its body')
        page.keyboard.type('ggzo')
        check(page.locator('.cm-foldPlaceholder').count() == 0, 'zo opens the current Markdown section')
        page.keyboard.type('zaza')
        check(page.locator('.cm-foldPlaceholder').count() == 0, 'za toggles a section closed then open')
        page.keyboard.type('zM')
        check(page.locator('.cm-foldPlaceholder').count() >= 2, 'zM closes Markdown sections across the document')
        page.keyboard.type('zR')
        check(page.locator('.cm-foldPlaceholder').count() == 0, 'zR opens all Markdown sections')
        page.locator('.sac-section-gutter button').first.click()
        check(page.locator('.cm-foldPlaceholder').count() == 1, 'header fold controls support mouse use')
        page.locator('.sac-section-gutter button').first.click()
        page.keyboard.press(':')
        page.wait_for_function('document.querySelector("#picker").open')
        check(page.locator('#picker-preview').is_hidden() and page.locator('#picker').evaluate('(node) => node.classList.contains("commands")'), 'colon commands use a compact list without an unused preview column')
        page.keyboard.type('vsplit'); page.keyboard.press('Enter')
        check(len(state(page)['panes']) == 2, 'vsplit opens a pane beside the current document')
        page.keyboard.press('Control+w'); page.keyboard.press('s')
        check(len(state(page)['panes']) == 3, 'delivered Ctrl+W s splits below')
        page.keyboard.press('Control+w'); page.keyboard.press('c')
        check(len(state(page)['panes']) == 2, 'delivered Ctrl+W c closes the current pane')
        command(page, 'only'); command(page, 'vs'); command(page, 'close'); command(page, 'sp')
        check(len(state(page)['panes']) == 2, 'vs sp close and only aliases compose without changing the document')
        command(page, 'only'); command(page, 'vs')
        leader(page, 'uv')
        page.wait_for_function('document.querySelector(".pane.active .draft-body")?.textContent.includes("Implementation.")')
        body = page.locator('.pane.active .draft-body'); previous = body.inner_html()
        leader(page, 'wh')
        held = []
        def delay_updates(route):
            response = route.fetch(); held.append((route, response))
            route.request.frame.evaluate('window.workbenchDraftUpdatesHeld = true')
        page.route('**/workbench/preview', delay_updates)
        before = request(base + '/api/v1/workbench')[1]['cursor']
        page.keyboard.type('ggA'); page.keyboard.insert_text(' Added.'); page.keyboard.press('Escape')
        page.wait_for_function('window.workbenchDraftUpdatesHeld === true')
        check(page.locator('.pane:not(.active) .draft-body').inner_html() == previous and 'Rendering draft' not in page.locator('.pane:not(.active) .reading').inner_text(), 'typing retains the last rendered draft instead of flashing loading text')
        for route, response in reversed(held): route.fulfill(response=response)
        page.unroute('**/workbench/preview', delay_updates)
        page.wait_for_function('document.querySelector(".pane:not(.active) .draft-body").textContent.includes("Added.")')
        check(request(base + '/api/v1/workbench')[1]['cursor'] == before and draft(page)['text'].startswith('# Plan Added.'), 'preview refresh preserves edits and writes no records')
        page.screenshot(path=str(run / '08-editor-sections-and-preview.png'))
    finally:
        context.close()
    touch = browser.new_context(viewport={'width': 390, 'height': 844}, is_mobile=True, has_touch=True)
    try:
        page = touch.new_page(); page.goto(base)
        page.wait_for_function('window.workbenchUI !== undefined')
        page.tap('#open-commands')
        page.wait_for_function('document.querySelector("#picker").open')
        page.keyboard.type('new note')
        check(page.locator('#results button').first.bounding_box()['height'] >= 40, 'touch palette exposes full-sized actions without a permanent toolbar')
        page.keyboard.press('Enter')
        before = request(base + '/api/v1/workbench')[1]['cursor']
        page.keyboard.insert_text('Capture a thought.')
        leader(page, 'uv')
        page.wait_for_function('document.querySelector(".pane.active .draft-body")?.textContent.includes("Capture a thought.")')
        check(draft(page)['text'] == 'Capture a thought.' and state(page)['mode'] == 'View', 'touch actions can create edit and view a draft')
        check(request(base + '/api/v1/workbench')[1]['cursor'] == before and page.evaluate('document.documentElement.scrollWidth <= innerWidth'), 'touch draft viewing neither publishes nor overflows the viewport')
        page.screenshot(path=str(run / '09-touch-palette.png'))
    finally:
        touch.close()


def finder(page, query):
    page.keyboard.press('Escape')
    page.keyboard.press('Space')
    page.keyboard.press('Space')
    page.wait_for_function('document.querySelector("#picker").open')
    page.keyboard.type(query)
